#!/usr/bin/env python3
"""Generate native Claude, Codex and Copilot instructions; stdlib only.

Adapted from the supplied AI Folder Pattern v1 / sync script v2. Root overlays
are vendor-specific; scoped rules use the portable subset ** or directory/**.
No Git metadata is needed except for the optional staged-index check.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path, PurePosixPath

VERSION = "3.1.0"
TAG = "<!-- AUTO-GENERATED by scripts/sync-ai-instructions.sh -->"
TARGETS = {
    "claude": ("CLAUDE.md", ".claude/rules", ".claude/skills"),
    "codex": ("AGENTS.md", None, ".agents/skills"),
    "copilot": (".github/copilot-instructions.md", ".github/instructions", ".github/skills"),
}
KINDS = ("instructions", "skills", "native")
NATIVE_ROOTS = {"claude": ".claude", "codex": ".codex", "copilot": ".github"}
# Bound native ownership to repository setup, never personal permissions or CI.
NATIVE_PATHS = {
    "claude": (".claude/config.json", ".claude/settings.json", ".claude/setup.sh",
               ".claude/hooks/", ".claude/agents/"),
    "codex": (".codex/codex.json", ".codex/setup.sh", ".codex/agents/"),
    "copilot": (".github/agents/",),
}
VENDOR_TERMS = {
    "claude": r"claude(?:_[a-z0-9_]+)?|anthropic|sonnet|opus|superpowers",
    "codex": r"codex(?:_[a-z0-9_]+)?|openai|gpt-[0-9][\w.-]*|AGENTS\.md|\.agents(?=/)",
    "copilot": r"copilot",
}


def validate_vendor(text: str, vendor: str, source: str) -> None:
    for other, terms in VENDOR_TERMS.items():
        if other != vendor and re.search(
                rf"(?i)(?<![a-z0-9_])(?:{terms})(?![a-z0-9_])", text):
            raise ValueError(f"{source}: foreign vendor guidance ({other}) in {vendor} output; "
                             "keep shared sources neutral and use the matching vendor source")


def safe_path(root: Path, name: str) -> Path:
    parts = PurePosixPath(name).parts
    if (not parts or PurePosixPath(name).is_absolute() or "\\" in name or ":" in name
            or any(p in {".", "..", ".git"} for p in name.split("/"))
            or name.casefold() == "docs/experiments"
            or name.casefold().startswith("docs/experiments/")):
        raise ValueError(f"unsafe or excluded path: {name}")
    path = root
    for part in parts:
        path /= part
        if path.is_symlink():
            raise ValueError(f"symlinks are not supported: {name}")
    return path


def read(root: Path, name: str) -> str:
    return safe_path(root, name).read_text(encoding="utf-8")


def split_frontmatter(text: str, source: str) -> tuple[str, str]:
    lines = text.splitlines()
    if not lines or lines[0] != "---":
        raise ValueError(f"{source}: frontmatter must start on line 1")
    try:
        end = lines.index("---", 1)
    except ValueError:
        raise ValueError(f"{source}: unclosed frontmatter") from None
    return "\n".join(lines[1:end]), "\n".join(lines[end + 1:]).strip() + "\n"


def scoped(text: str, source: str) -> tuple[list[str], str]:
    front, body = split_frontmatter(text, source)
    match = re.fullmatch(r'''applyTo:\s*(["'])([^\n]+)\1\s*''', front)
    if not match:
        raise ValueError(f"{source}: expected only a quoted applyTo field")
    patterns = [p.strip() for p in match[2].split(",")]
    for pattern in patterns:
        if pattern == "**" and len(patterns) == 1:
            continue
        if not re.fullmatch(r"[A-Za-z0-9_-]+(?:/[A-Za-z0-9_-]+)*/\*\*", pattern):
            raise ValueError(f"{source}: {pattern!r} cannot map exactly to Codex directory scope; "
                             "use ** alone or directory/**")
        if pattern.casefold().startswith("docs/experiments/"):
            raise ValueError(f"{source}: excluded scope: {pattern}")
    return list(dict.fromkeys(patterns)), body


def marked(body: str, sources: list[str], front: str = "") -> str:
    prefix = f"---\n{front}\n---\n\n" if front else ""
    return (prefix + TAG + "\n> GENERATED FILE. DO NOT EDIT. Sources: "
            + ", ".join(f"`{s}`" for s in sources)
            + ".\n> Edit the sources and run `sh scripts/sync-ai-instructions.sh`.\n\n"
            + body.strip() + "\n")


def instruction_outputs(root: Path, vendor: str) -> dict[str, str]:
    base = ".ai/instructions"
    common = read(root, f"{base}/root.md")
    if common.startswith("---"):
        raise ValueError("root.md must not have frontmatter")
    sources = [f"{base}/root.md"]
    sections = [common]
    rules = []
    for path in sorted(safe_path(root, base).glob("*.md")):
        if path.name in {"root.md", "README.md"}:
            continue
        source = f"{base}/{path.name}"
        patterns, body = scoped(read(root, source), source)
        if patterns == ["**"]:
            sources.append(source)
            sections.append(body)
        else:
            rules.append((path.stem, source, patterns, body))
    overlay = f".ai/vendors/{vendor}-policy.md"
    sections.append(read(root, overlay))
    sources.append(overlay)
    index = ["## Scoped instruction index", "",
             "Before editing a matching path, read the listed source if its native rule "
             "was not loaded. Paths are relative to the repository root.", "",
             "| Source | Scope |", "|---|---|"]
    index += [f"| `{source}` | `{','.join(patterns)}` |"
              for _, source, patterns, _ in rules]
    sections.append("\n".join(index))
    root_name, rule_dir, _ = TARGETS[vendor]
    outputs = {root_name: marked("\n\n".join(sections), sources)}
    directories: dict[str, list[tuple[str, str]]] = {}
    for name, source, patterns, body in rules:
        if vendor == "codex":
            for pattern in patterns:
                path = pattern[:-3] + "/AGENTS.md"
                safe_path(root, path)
                directories.setdefault(path, []).append((source, body))
        elif vendor == "claude":
            front = "paths:\n" + "\n".join(f"  - {json.dumps(p)}" for p in patterns)
            outputs[f"{rule_dir}/{name}.md"] = marked(body, [source], front)
        else:
            front = "applyTo: " + json.dumps(",".join(patterns))
            outputs[f"{rule_dir}/{name}.instructions.md"] = marked(body, [source], front)
    for path, entries in directories.items():
        outputs[path] = marked("\n\n".join(body for _, body in entries),
                               [source for source, _ in entries])
    for name, text in outputs.items():
        validate_vendor(name + "\n" + text, vendor, name)
    return outputs


def skill_outputs(root: Path, vendor: str) -> dict[str, str]:
    outputs = {}
    source_dir = safe_path(root, ".ai/skills")
    if not source_dir.exists():
        return outputs
    for directory in sorted(source_dir.iterdir()):
        if directory.name == "README.md":
            continue
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", directory.name):
            raise ValueError(f"invalid skill directory: {directory.name}")
        source = f".ai/skills/{directory.name}/SKILL.md"
        front, body = split_frontmatter(read(root, source), source)
        for field in ("name", "description"):
            if not re.search(rf"(?m)^{field}:\s*\S", front):
                raise ValueError(f"{source}: missing {field}")
        dest = f"{TARGETS[vendor][2]}/{directory.name}"
        outputs[f"{dest}/SKILL.md"] = marked(body, [source], front)
        # Deliberately bounded: only SKILL.md and Markdown references are supported.
        for path in sorted(directory.iterdir()):
            if path.name == "SKILL.md":
                continue
            if path.name != "references":
                raise ValueError(f"unsupported skill asset: {path.name}")
            references = safe_path(root, f".ai/skills/{directory.name}/references")
            for ref in sorted(references.iterdir()):
                if ref.suffix != ".md" or not ref.is_file():
                    raise ValueError(f"unsupported reference: {ref.name}")
                outputs[f"{dest}/references/{ref.name}"] = read(
                    root, f".ai/skills/{directory.name}/references/{ref.name}")
    for name, text in outputs.items():
        validate_vendor(name + "\n" + text, vendor, name)
    return outputs


def native_outputs(root: Path, vendor: str) -> dict[str, str]:
    base = f".ai/vendors/{vendor}/native"
    directory = safe_path(root, base)
    outputs = {}
    if not directory.exists():
        return outputs
    for path in sorted(directory.rglob("*")):
        relative = path.relative_to(directory).as_posix()
        source = f"{base}/{relative}"
        safe_path(root, source)
        if path.is_dir():
            continue
        dest = f"{NATIVE_ROOTS[vendor]}/{relative}"
        if not owned_path(dest, vendor, "native"):
            raise ValueError(f"{source}: unsupported native output: {dest}")
        text = read(root, source)
        validate_vendor(dest + "\n" + text, vendor, source)
        outputs[dest] = text
    return outputs


def digest(text: str) -> str:
    return base64.b64encode(hashlib.sha256(text.encode("utf-8")).digest()).decode("ascii")


def owned_path(name: str, vendor: str, kind: str) -> bool:
    root_name, rules, skills = TARGETS[vendor]
    if kind == "native":
        return (".local." not in name and any(
            name == p or (p.endswith("/") and name.startswith(p))
            for p in NATIVE_PATHS[vendor]))
    if kind == "skills":
        return name.startswith(skills + "/") and name.endswith(".md")
    if name == root_name:
        return True
    if vendor == "codex":
        return bool(re.fullmatch(r"(?:[A-Za-z0-9_-]+/)+AGENTS\.md", name))
    return name.startswith(str(rules) + "/") and name.endswith(".md")


def plan(root: Path, vendor: str, kind: str) -> tuple[dict[str, str], list[str]]:
    output = {"instructions": instruction_outputs, "skills": skill_outputs,
              "native": native_outputs}[kind](root, vendor)
    manifest_name = f".ai/generated/{vendor}-{kind}.json"
    manifest = safe_path(root, manifest_name)
    previous = {}
    if manifest.exists():
        data = json.loads(manifest.read_text(encoding="utf-8"))
        if (not isinstance(data, dict) or data.get("version") != 1
                or not isinstance(data.get("files"), dict)
                or not all(isinstance(value, str) for value in data["files"].values())):
            raise ValueError(f"invalid ownership manifest: {manifest_name}")
        previous = data["files"]
    for name in previous:
        safe_path(root, name)
        if not owned_path(name, vendor, kind):
            raise ValueError(f"invalid owned path in {manifest_name}: {name}")
    obsolete = sorted(set(previous) - set(output))
    for name in obsolete:
        path = safe_path(root, name)
        if path.exists() and digest(read(root, name)) != previous[name]:
            raise ValueError(f"refusing to delete modified obsolete output: {name}")
    for name, text in output.items():
        path = safe_path(root, name)
        if path.exists():
            current = read(root, name)
            if (current != text and not (kind == "native" and name in previous)
                    and TAG not in current.splitlines()[:30]
                    and digest(current) != previous.get(name)):
                raise ValueError(f"refusing to overwrite hand-authored file: {name}")
    output[manifest_name] = json.dumps(
        {"version": 1, "files": {name: digest(text) for name, text in sorted(output.items())}},
        indent=2) + "\n"
    return output, obsolete


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=".ai-sync-", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        # Atomic replacement must keep hooks executable.
        mode = path.stat().st_mode & 0o777 if path.exists() else (
            0o755 if path.suffix == ".sh" else 0o644)
        os.chmod(name, mode)
        os.replace(name, path)
    finally:
        Path(name).unlink(missing_ok=True)


def staged_check(root: Path, args) -> int:
    """Check exactly the index, never restage or change the working tree."""
    listing = subprocess.run(["git", "ls-files", "--stage", "-z"], cwd=root,
                             check=True, capture_output=True).stdout.decode("utf-8")
    with tempfile.TemporaryDirectory(prefix="ai-index-") as directory:
        snapshot = Path(directory)
        for record in filter(None, listing.split("\0")):
            metadata, name = record.split("\t", 1)
            mode, _, stage = metadata.split()
            relevant = (name.startswith(".ai/") or name in {
                "scripts/sync_ai_instructions.py", "scripts/sync-ai-instructions.sh"}
                or any(owned_path(name, v, k) for v in TARGETS for k in KINDS))
            if not relevant:
                continue
            path = safe_path(snapshot, name)
            if mode == "120000" or stage != "0":
                raise ValueError(f"symlink or unmerged instruction in index: {name}")
            content = subprocess.run(["git", "show", f":{name}"], cwd=root,
                                     check=True, capture_output=True).stdout
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
            if mode == "100755":
                path.chmod(0o755)
        command = [sys.executable, str(snapshot / "scripts/sync_ai_instructions.py"), "--check"]
        command += [f"--{v}" for v in TARGETS if getattr(args, v)]
        if args.skills:
            command.append("--skills")
        return subprocess.run(command, cwd=snapshot).returncode


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--check", action="store_true")
    modes.add_argument("--dry-run", action="store_true")
    parser.add_argument("--staged", action="store_true", help="check staged sources and outputs")
    for vendor in TARGETS:
        parser.add_argument(f"--{vendor}", action="store_true")
    parser.add_argument("--skills", action="store_true", help="only sync optional skills")
    parser.add_argument("--version", action="version", version=VERSION)
    args = parser.parse_args(argv)
    if args.staged and not args.check:
        parser.error("--staged requires --check")
    root = Path(__file__).resolve().parent.parent
    try:
        if args.staged:
            return staged_check(root, args)
        vendors = [v for v in TARGETS if getattr(args, v)] or list(TARGETS)
        writes, removals = {}, []
        # Preflight every selected target before performing any mutation.
        for vendor in vendors:
            for kind in (["skills"] if args.skills else KINDS):
                output, obsolete = plan(root, vendor, kind)
                writes.update(output)
                removals.extend(obsolete)
        changed = {name: text for name, text in writes.items()
                   if not safe_path(root, name).exists() or read(root, name) != text}
        removals = [name for name in removals if safe_path(root, name).exists()]
        for name in changed:
            print(f"{'STALE' if args.check else 'WRITE'}: {name}")
        for name in removals:
            print(f"{'STALE' if args.check else 'REMOVE'}: {name}")
        if args.check:
            return int(bool(changed or removals))
        if not args.dry_run:
            for name, text in changed.items():
                atomic_write(safe_path(root, name), text)
            for name in removals:
                safe_path(root, name).unlink()
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        print(f"ai-sync: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
